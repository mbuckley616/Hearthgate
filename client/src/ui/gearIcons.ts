const css = (n: number) => `#${n.toString(16).padStart(6, '0')}`;

/** Mix a colour toward white (amount > 0) or black (amount < 0). */
function shade(n: number, amount: number): string {
  const to = amount > 0 ? 255 : 0;
  const a = Math.abs(amount);
  const ch = (shift: number) => Math.round(((n >> shift) & 255) * (1 - a) + to * a);
  return css((ch(16) << 16) | (ch(8) << 8) | ch(0));
}

const cache = new Map<string, string>();

/** The item's icon as a data URL, or null for a shape with no grid yet (the cell falls back to a swatch). */
export function gearIconUrl(e: CatalogueEntry): string | null {
  const hit = cache.get(e.id);
  if (hit !== undefined) return hit;
  const rows = SHAPE_ICONS[e.shape.id];
  if (!rows) return null;
  const { base, trim } = e.material.colors;
  const colors: Record<string, string> = { ...FIXED, B: css(base), H: shade(base, 0.35), D: shade(base, -0.35), T: css(trim) };
  const c = document.createElement('canvas');
  c.width = c.height = 16;
  const g = c.getContext('2d')!;
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      const color = colors[row[x]];
      if (!color) continue;
      g.fillStyle = color;
      g.fillRect(x, y, 1, 1);
    }
  });
  const url = c.toDataURL();
  cache.set(e.id, url);
  return url;
}
